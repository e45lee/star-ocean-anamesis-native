# ---------------------------------------------------------------- story (phase 2: C3, E7, M4)
#
# data/english/story/TS_xxxx.tsv     the machine/human/reviewed rows of one Scenario file (TABLE_COLS;
#                                     no Japanese: the story's Japanese is not in git, english.md 7.6)
# data/english/story-en/TS_xxxx.tsv  GENERATED: message_id, ja_sha1, en, source of every line of the
#                                     file that has English (official, E3, table rows), after the
#                                     strict story checks and the re-break to the message window
# data/english/story-en/index.tsv    GENERATED: file, lines, need (lines with kana or kanji),
#                                     english (of those, lines with a row), complete (yes|no): the
#                                     server serves TS_x-en.msgp only when complete (Q12)
# A story line's ja_sha1 is the SHA-1 of the Scenario row's text_value exactly as the file holds it
# (UTF-8, REAL newlines), unlike the master's two-character \n. The Japanese comes from the 3.7.0
# download (Scenario/ in work/SOA-3.7.0-canonical-data.zip) at build time; without it the story part is skipped.

STORY_BUDGET = 480   # px per line of the message window (font px; measured on a --lang en campaign shot, english.md 7.5)
# (d) <player> expands to the player's name: counted as 120 px (about 8 Latin letters) when breaking
PLAYER_PX = {"<player>": 120}
STORY_SOURCES = ("official", "machine", "agent", "human", "reviewed")
STORY_LONG = 5       # lines: a served line needing this many or more is reported (E7)
# E13: the window holds STORY_LINES lines; n lines are 40 n - 10 high at its FontSize 30 (lines 40
# apart, 30 high: CEventScenarioMessageWindow::Show, CalcStringRect; (b) client evidence). A line
# over STORY_LINES lines gets the font scale k_n = (40 * 4 - 10) / (40 n - 10) from the client
# (platform370 text_370.cpp h_window_change), so it is broken at STORY_BUDGET / k_n, for the fewest
# n that holds it (english.md 7.13).
STORY_LINES = 4


def story_budget(n):
    """The break width for n window lines: STORY_BUDGET up to STORY_LINES lines, else STORY_BUDGET /
    k_n = STORY_BUDGET * (40 n - 10) // (40 * STORY_LINES - 10) (an integer: 128 n - 32)."""
    return STORY_BUDGET if n <= STORY_LINES else STORY_BUDGET * (40 * n - 10) // (40 * STORY_LINES - 10)


def story_break(font, e):
    """`e` broken for the message window (E7, E13): for the fewest n (1, 2, ...) whose break at
    story_budget(n) takes at most n lines (the greedy break never gains lines at a wider width, so
    that is the largest font the client can give it)."""
    for n in range(1, 25):
        r = font.rebreak(e, story_budget(n), PLAYER_PX)
        if r.count("\n") + 1 <= n:
            return r
    return r


def story_finish(ctx, glossary, source, en, ja):
    """(served English in the two-character \\n encoding, problems, number of lines) of a story
    candidate; `ja` with real newlines. Every line is re-broken at spaces to STORY_BUDGET (Global's
    breaks were made for a wider window, english.md 6.5)."""
    font = ctx.fnt
    e = C.unesc(en)
    if source in HUMAN or source in MACHINE:
        e = unicodedata.normalize("NFC", e)
    e = font.fold(e).strip()
    e = story_break(font, e)
    probs = C.check(ja, e, font, glossary if source not in DERIVED else None, tags="strict")
    tags = C.TAG.findall(e)
    bad = [t for t in tags if not C.STORY_TAG.fullmatch(t)]
    if source in MACHINE and C.runaway(ja, e):
        probs["runaway"] = len(e)  # an engine stuck repeating a sound ("CAPTAIIII...", "ka-ka-ka-...")
    if bad:
        probs["story_tag"] = bad  # an unknown tag likely crashes ParseMessage (english.md 3.3)
    elif source not in MACHINE and "tags" in probs:
        # Global's (and a person's) English may colour other words or name <player> where JP says
        # 艦長: harmless as long as every tag is one ParseMessage reads and <font> is balanced.
        # An engine must keep the Japanese line's tags exactly.
        opens = sum(1 for t in tags if t.startswith("<font"))
        if opens == tags.count("</font>"):
            del probs["tags"]
    return C.esc(e), probs, e.count("\n") + 1


class StoryDerived:
    """Per story line: file, Japanese, sha1, class and the official candidate (Global by id or E3),
    finished; cached per Sources like Derived. None without the Scenario files."""

    def __init__(self, ctx):
        src = ctx.src
        self.lines = {}       # mid -> (stem, ja, sha1, klass, [(source, en, probs, nlines)])
        self.files = collections.defaultdict(list)
        self.token_gaps = []
        for stem, mid, ja in src.story():
            cands, klass = [], None
            en = src.story_official(mid, ja)
            if en is not None:
                klass = "official"
            else:
                en, why = src.story_official_e3(mid, ja)
                if en is not None:
                    klass = "official_e3"
                elif why:
                    self.token_gaps.append((mid, C.esc(ja), src.gl_en.get(mid, ""), why))
            if en is not None:
                cands.append(("official",) + story_finish(ctx, None, "official", en, ja))
            if klass is None:
                klass = "gap" if C.has_kana(ja) else "neutral"
            elif not C.has_kana(ja):
                klass = "neutral"  # language-neutral (……, ！？): served if Global has English, never needed
            self.lines[mid] = (stem, ja, C.sha1(ja), klass, cands)
            self.files[stem].append(mid)

    @staticmethod
    def of(ctx):
        if not ctx.src.has_story():
            return None
        cache = ctx.src.__dict__.setdefault("_english_story", {})
        key = str(ctx.font)
        if key not in cache:
            cache[key] = StoryDerived(ctx)
        return cache[key]


def build_story(ctx, glossary, tables=None):
    """The story part of a build, or None without the Scenario files."""
    d = StoryDerived.of(ctx)
    if d is None:
        return None
    tables = ctx.story_tables() if tables is None else tables
    s = Built()
    s.derived = d
    s.out = {}            # mid -> (ja_sha1, en, source)
    s.ours = {}           # the same for our rows (story/TS_*.tsv) that pass
    s.failures, s.stale, s.long = [], [], []
    s.files = {}          # stem -> counts
    for mid, t in sorted(tables.items()):
        if mid not in d.lines:
            s.stale.append((mid, t["source"], t["ja_sha1"], ""))
    for stem in sorted(d.files):
        c = collections.Counter()
        for mid in d.files[stem]:
            _, ja, h, klass, derived = d.lines[mid]
            c["lines"] += 1
            if klass != "neutral":
                c["need"] += 1
            t = tables.get(mid)
            if t and t["ja_sha1"] != h:
                s.stale.append((mid, t["source"], t["ja_sha1"], h))
                t = None
            cands = []
            if t and t["source"] in HUMAN:
                cands.append((t["source"], t["en"]))
            cands += derived
            if t and t["source"] in MACHINE:
                cands.append((t["source"], t["en"]))
            if t:  # our row, committed whenever it passes (even where a derived line wins)
                e, probs, _ = story_finish(ctx, glossary, t["source"], t["en"], ja)
                if not probs:
                    s.ours[mid] = (h, e, t["source"])
            failed = False
            for cand in cands:
                if len(cand) == 2:
                    source = cand[0]
                    e, probs, nl = story_finish(ctx, glossary, source, cand[1], ja)
                else:
                    source, e, probs, nl = cand
                if probs:
                    s.failures.append({"message_id": mid, "file": stem, "source": source, "en": e, "problems": probs})
                    failed = True
                    continue
                s.out[mid] = (h, e, source)
                c[source] += 1
                if klass != "neutral":
                    c["english"] += 1
                if nl >= STORY_LONG:
                    s.long.append((mid, stem, source, nl, e))
                break
            else:
                if klass != "neutral":
                    c["failing" if failed else "missing"] += 1
        s.files[stem] = c
    def texts(rows_of):
        out = {}
        for stem in sorted(d.files):
            rows = [{"message_id": m, "ja_sha1": rows_of[m][0], "en": rows_of[m][1], "source": rows_of[m][2]}
                    for m in sorted(d.files[stem], key=lambda m: m.encode()) if m in rows_of]
            if rows:
                out[stem] = tsv_text(OUT_COLS, rows)
        return out
    s.texts = texts(s.ours)        # committed: data/english/story-en/TS_*.tsv, our rows only
    s.full_texts = texts(s.out)    # `derive`: story-en-full/TS_*.tsv
    s.index = tsv_text(["file", "lines", "need", "english", "complete"],
                       [{"file": stem, "lines": c["lines"], "need": c["need"], "english": c["english"],
                         "complete": "yes" if c["english"] == c["need"] else "no"}
                        for stem, c in sorted(s.files.items())])
    return s


def story_outputs(ctx, s):
    """{path: text} of the committed story files: our rows per Scenario file."""
    return {ctx.path("story-en") / f"{stem}.tsv": text for stem, text in s.texts.items()}


def write_story(ctx, s):
    outs = story_outputs(ctx, s)
    for p, text in outs.items():
        write_if_changed(p, text)
    for p in list(ctx.path("story-en").glob("TS_*.tsv")) + [ctx.path("story-en") / "index.tsv"]:
        if p.exists() and p not in outs:
            p.unlink()  # a file with none of our rows any more (index.tsv: now derive's)


def story_summary(s):
    if s is None:
        return "story: skipped (no Scenario files: work/SOA-3.7.0-canonical-data.zip)"
    tot = collections.Counter()
    for c in s.files.values():
        tot.update(c)
    complete = sum(1 for c in s.files.values() if c["english"] == c["need"])
    return (f"story: {tot['english']} of {tot['need']} lines English ("
            + ", ".join(f"{k} {tot[k]}" for k in C_SOURCES if tot[k])
            + f"), {tot['failing']} failing, {complete} of {len(s.files)} files complete, "
            f"{len(s.long)} lines of {STORY_LONG}+ lines, {len(s.stale)} stale table rows")


def cmd_build(ctx, a):
    b = build(ctx)
    s = build_story(ctx, b.glossary)
    if a.check:
        want = {ctx.path("master-en.tsv"): b.master_en, ctx.path("glossary.tsv"): b.glossary_text}
        if s is not None:
            want.update(story_outputs(ctx, s))
            extra = [p for p in list(ctx.path("story-en").glob("TS_*.tsv")) + [ctx.path("story-en") / "index.tsv"]
                     if p.exists() and p not in want]
        else:
            extra = []
        bad = [str(p.relative_to(ctx.data)) for p, text in want.items()
               if not p.exists() or p.read_text(encoding="utf-8") != text] + [str(p) for p in extra]
        if bad:
            print(f"stale: {', '.join(bad[:10])} (run tools/english_text.py build)", file=sys.stderr)
            return 1
        print("data/english is fresh: " + summary(b) + "\n" + story_summary(s))
        return 0
    write_build(ctx, b)
    if s is not None:
        write_story(ctx, s)
    print(summary(b) + "\n" + story_summary(s))
    return 0


def derive(ctx, out_dir):
    """The FULL resolved tables, official / memory / template included: master-en-full.tsv and
    story-en-full/TS_*.tsv (+ index.tsv), in the format of master-en.tsv. Not committed: the
    reference the server's C++ derivation (docs/english.md 7.6 "The derivation") is compared with."""
    out_dir = pathlib.Path(out_dir)
    b = build(ctx)
    write_if_changed(out_dir / "master-en-full.tsv", b.master_en_full)
    s = build_story(ctx, b.glossary)
    if s is not None:
        d = out_dir / "story-en-full"
        for stem, text in s.full_texts.items():
            write_if_changed(d / f"{stem}.tsv", text)
        for p in d.glob("TS_*.tsv"):
            if p.stem not in s.full_texts:
                p.unlink()
        write_if_changed(d / "index.tsv", s.index)
    return b, s


def cmd_derive(ctx, a):
    b, s = derive(ctx, a.out)
    print(f"{a.out}: master-en-full.tsv {len(b.out)} rows; " + story_summary(s))
    return 0


def rebuild(ctx, a):
    if not getattr(a, "no_build", False):
        b = build(ctx)
        write_build(ctx, b)
        s = build_story(ctx, b.glossary)
        if s is not None:
            write_story(ctx, s)
        print(summary(b) + "\n" + story_summary(s))


