def export_rows(ctx, b):
    """(mid, ja (master encoding) or "", served en, source) of every row to edit: JP rows with kana
    or kanji or with English, then the new message_ids."""
    src = ctx.src
    for mid in sorted(src.jp_rows):
        ja = src.jp_rows[mid] or ""
        if mid in b.out or C.has_kana(ja):
            o = b.out.get(mid)
            yield mid, ja, o[1] if o else "", o[2] if o else "japanese"
    for mid in sorted(set(b.out) - set(src.jp_rows)):
        yield mid, "", b.out[mid][1], b.out[mid][2]


def export_story_rows(ctx, sb):
    """(file, mid, ja (real newlines), served en (two-character \\n), source) of every story line
    with kana or kanji or with English; nothing without the Scenario files."""
    if sb is None:
        return
    d = sb.derived
    for stem in sorted(d.files):
        for mid in d.files[stem]:
            ja = d.lines[mid][1]
            o = sb.out.get(mid)
            if o or C.has_kana(ja):
                yield stem, mid, ja, o[1] if o else "", o[2] if o else "japanese"


