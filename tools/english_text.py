#!/usr/bin/env python3
"""The English text table: build, report and edit (docs/english.md 7.6, PLAN-english.md E1/M1/E3).

Files (data/english/, committed):
  master.tsv          the rows a person or an engine wrote: message_id, ja_sha1, en, source
                      (machine | human | reviewed), engine, date, editor, note. Official, memory and
                      template English is NOT stored: the build derives it from the two master DBs.
  glossary.tsv        ja, en, kind, variants, source (official | human | machine), note. The official
                      rows are regenerated by `build` from Global (Q8); human and machine rows are kept.
  client-strings.tsv  message_id, en, note: the client's new strings (port_en_*), merged as human
                      rows with an empty ja_sha1.
  master-en.tsv       GENERATED by `build`: message_id, ja_sha1, en, source; every row that ends up
                      English after the checks, sorted by message_id. The server serves exactly this.
All TSVs: UTF-8, a header line, no quoting, a line break inside a text is the two characters \\n.

Precedence per message_id (english.md 7.6): human/reviewed > official (Global by id, the five
filters; plus Global token rows rewritten by E3) > memory (exact) / template > machine > Japanese.
A candidate that fails a check (english.md 7.5) is not served; the next one is tried, and the failure
is listed by `report`. A table row whose ja_sha1 differs from the current Japanese is stale: not served.

Usage:
  tools/english_text.py build [--check]          write master-en.tsv and glossary.tsv's official rows
                                                 (--check: exit 1 when the committed files are stale)
  tools/english_text.py report [--out DIR]       coverage per source and prefix, failing rows, width
                                                 outliers, Q7 rows, token gaps, glossary conflicts
                                                 (summary to stdout, lists to work/english/report/)
  tools/english_text.py show ID
  tools/english_text.py set ID TEXT --by NAME [--note N] [--force]
  tools/english_text.py review ID... --by NAME   machine -> reviewed (kept unchanged)
  tools/english_text.py stale                    table rows whose Japanese changed
  tools/english_text.py export-po [--out DIR]    one .po per prefix (work/english/po/)
  tools/english_text.py import-po FILE... --by NAME
  tools/english_text.py export-csv [--out FILE]  (work/english/english.csv)
  tools/english_text.py import-csv FILE --by NAME
  tools/english_text.py import-mt CHECKPOINT.jsonl [--replace]
                                                 machine rows from the MT runner's checkpoint; rows
                                                 failing the checks go to work/english/mt-rejected.tsv
Common options: --data DIR (data/english) --master DB --gl DB --scenario DIR --font FILE --no-build
"""
