    d = s.derived
    tables = ctx.story_tables()
    rej_path = ctx.work / "mt-rejected-story.tsv"
    rejected = {r["message_id"]: r for r in read_tsv(rej_path, REJECT_COLS)}
    for r in rows:
        engine = engine_name(r)
        for ln in r["lines"]:
            mid = ln["message_id"]
            if mid not in d.lines:
                n["story: not in the Scenario files"] += 1
                continue
            stem, ja, h, klass, _ = d.lines[mid]
            if ln["ja_sha1"] != h:
                n["story: hash mismatch"] += 1
                continue
            t = tables.get(mid)
            if t and t["source"] in HUMAN:
                n["story kept: human/reviewed"] += 1
                continue
            served = s.out.get(mid)
            if served and served[2] in DERIVED + HUMAN:
                n["story kept: covered by " + served[2]] += 1
                continue
            if not ln.get("mt"):
                n["story: skipped by the model"] += 1
                continue
            if t and t["source"] == "machine":
                if not a.replace:
                    n["story kept: machine row exists"] += 1
                    continue
                if t["ja_sha1"] == h and t["engine"] == engine:
                    n["story kept: same hash, engine and prompt"] += 1
                    continue
            e, probs, _ = story_finish(ctx, b.glossary, "machine", C.esc(ln["mt"]), ja)
            if probs:
                rejected[mid] = {"message_id": mid, "ja_sha1": h, "engine": engine, "date": r.get("date", ""),
                                 "en": e, "problems": json.dumps(probs, ensure_ascii=False)}
                n["story rejected"] += 1
                continue
            rejected.pop(mid, None)
            tables[mid] = {"message_id": mid, "ja_sha1": h, "en": e, "source": "machine", "engine": engine,
                           "date": r.get("date", ""), "editor": "", "note": "", "file": stem}
            n["story imported"] += 1
    ctx.write_story_tables(tables)
    if rejected or rej_path.exists():
        rej_path.parent.mkdir(parents=True, exist_ok=True)
        rej_path.write_text(tsv_text(REJECT_COLS, [rejected[m] for m in sorted(rejected)]), encoding="utf-8")
    if n["story rejected"]:
        print(f"rejected story lines: {rej_path}", file=sys.stderr)


