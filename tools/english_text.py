# ---------------------------------------------------------------- TSV files

def _field(s):
    s = "" if s is None else str(s)
    if any(c in s for c in "\t\r\n"):
        raise ValueError(f"tab or line break in a field: {s!r}")
    return s


def tsv_text(cols, rows):
    out = ["\t".join(cols)]
    for r in rows:
        out.append("\t".join(_field(r.get(c, "")) for c in cols))
    return "\n".join(out) + "\n"


def read_tsv(path, cols, required=False):
    """[{col: value}] of a TSV with exactly this header; [] for a missing file unless required."""
    path = pathlib.Path(path)
    if not path.exists():
        if required:
            raise FileNotFoundError(path)
        return []
    lines = path.read_text(encoding="utf-8").split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    if not lines or lines[0].split("\t") != cols:
        raise ValueError(f"{path}: header must be {cols}")
    rows = []
    for n, line in enumerate(lines[1:], 2):
        f = line.split("\t")
        if len(f) != len(cols):
            raise ValueError(f"{path}:{n}: {len(f)} fields, want {len(cols)}")
        rows.append(dict(zip(cols, f)))
    return rows


def write_if_changed(path, text):
    path = pathlib.Path(path)
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return True


_SOURCES = {}  # read-only sources, shared by the commands of one process (the tests)


class Ctx:
    def __init__(self, data=DATA, master=C.MASTER_DB, gl=C.GLOBAL_DB, scenario=C.SCENARIO, font=None,
                 work=WORK):
        self.data = pathlib.Path(data)
        self.master, self.gl, self.scenario, self.font = master, gl, scenario, font
        self.work = pathlib.Path(work)
        self._src = self._font = None

    @property
    def src(self):
        if self._src is None:
            key = (str(self.master), str(self.gl), str(self.scenario))
            if key not in _SOURCES:
                _SOURCES[key] = C.Sources(master=self.master, gl=self.gl, scenario=self.scenario)
            self._src = _SOURCES[key]
        return self._src

    @property
    def fnt(self):
        if self._font is None:
            self._font = C.Font(self.font)
        return self._font

    def path(self, name):
        return self.data / name

    def table(self):
        rows = read_tsv(self.path("master.tsv"), TABLE_COLS)
        t = {}
        for r in rows:
            if r["message_id"] in t:
                raise ValueError(f"master.tsv: {r['message_id']} twice")
            if r["source"] not in MACHINE + HUMAN:
                raise ValueError(f"master.tsv: {r['message_id']}: source {r['source']!r} (machine|agent|human|reviewed)")
            t[r["message_id"]] = r
        return t

    def write_table(self, t):
        rows = [t[m] for m in sorted(t)]
        write_if_changed(self.path("master.tsv"), tsv_text(TABLE_COLS, rows))

    def story_tables(self):
        """{message_id: row} of data/english/story/TS_*.tsv; each row also carries its "file"."""
        t = {}
        for p in sorted(self.path("story").glob("TS_*.tsv")):
            for r in read_tsv(p, TABLE_COLS):
                if r["message_id"] in t:
                    raise ValueError(f"{p}: {r['message_id']} twice")
                if r["source"] not in MACHINE + HUMAN:
                    raise ValueError(f"{p}: {r['message_id']}: source {r['source']!r} (machine|agent|human|reviewed)")
                r["file"] = p.stem
                t[r["message_id"]] = r
        return t

    def write_story_tables(self, t):
        by = collections.defaultdict(list)
        for m in sorted(t):
            by[t[m]["file"]].append(t[m])
        for stem, rows in by.items():
            write_if_changed(self.path("story") / f"{stem}.tsv", tsv_text(TABLE_COLS, rows))
        for p in self.path("story").glob("TS_*.tsv"):
            if p.stem not in by:
                p.unlink()


# ---------------------------------------------------------------- glossary

def glossary_rows(ctx):
    """glossary.tsv's rows: Global's terms regenerated, the human and machine rows of the file kept."""
    src = ctx.src
    if not hasattr(src, "_english_glossary"):
        src._english_glossary = C.build_glossary(src)
    official = src._english_glossary
    rows = [{"ja": ja, "en": t["en"], "kind": t["kind"], "variants": " | ".join(t["variants"]),
             "source": "official", "note": ""} for ja, t in official.items()]
    for r in read_tsv(ctx.path("glossary.tsv"), GLOSSARY_COLS):
        if r["source"] == "official":
            continue
        if r["source"] not in GLOSSARY_RANK:
            raise ValueError(f"glossary.tsv: {r['ja']}: source {r['source']!r} (official|human|machine)")
        rows.append(r)
    rows.sort(key=lambda r: (r["ja"], GLOSSARY_RANK[r["source"]], r["en"]))
    return rows


WEAK_KINDS = ("ui", "skill", "talent", "speaker")  # not proper nouns of people, items, missions, areas
WEAK_MIN_ROWS, WEAK_MISS = 3, 0.5


def glossary_adherence(ctx, glossary):
    """{term: (rows, misses)}: how often Global's own official English (master rows by id and story
    lines) uses each glossary term's English where the Japanese has the term."""
    b = build(ctx)
    src = ctx.src
    n = collections.defaultdict(lambda: [0, 0])

    def acc(ja, en):
        miss = {t for t, _ in C.glossary_misses(ja, en, glossary)}
        for t in C.glossary_hits(ja, glossary):
            n[t][0] += 1
            n[t][1] += t in miss
    for mid, (h, e, source) in b.out.items():
        if source == "official" and mid in src.jp_rows:
            acc(C.unesc(src.jp_rows[mid]), C.unesc(e))
    s = build_story(ctx, b.glossary)
    if s is not None:
        for mid, (h, e, source) in s.out.items():
            if source == "official":
                acc(s.derived.lines[mid][1], C.unesc(e))
    return {t: tuple(v) for t, v in n.items()}


def cmd_glossary_weak(ctx, a):
    """The rule for demoting a Global glossary term (Q8 keeps Global's terms, but a term Global's own
    text doesn't follow only makes good MT rows fail): an official term of a kind in WEAK_KINDS whose
    English Global's official rows miss in at least half of at least 3 rows. Lists them (and the
    machine names Global's text contradicts); --apply adds a human row with an empty en for each
    weak term (a human row of the same term is left alone)."""
    rows = glossary_rows(ctx)
    official = glossary_dict([r for r in rows if r["source"] == "official"])
    machine = glossary_dict([r for r in rows if r["source"] == "machine"])
    adh = glossary_adherence(ctx, {**machine, **official})
    weak = [(t, official[t], adh[t]) for t in sorted(official)
            if official[t]["kind"] in WEAK_KINDS and t in adh and adh[t][0] >= WEAK_MIN_ROWS
            and adh[t][1] >= WEAK_MISS * adh[t][0]]
    contra = [(t, machine[t], adh[t]) for t in sorted(machine)
              if t not in official and t in adh and adh[t][0] >= WEAK_MIN_ROWS and adh[t][1] >= WEAK_MISS * adh[t][0]]
    humans = {r["ja"] for r in rows if r["source"] == "human"}
    print("weak official terms (Global's own rows miss them):")
    for t, g, (r, m) in weak:
        print(f"  {t}\t{g['en']}\t{g['kind']}\tmissed in {m} of {r}" + ("\t(has a human row)" if t in humans else ""))
    print("machine names Global's official text contradicts (give them Global's spelling as human rows):")
    for t, g, (r, m) in contra:
        print(f"  {t}\t{g['en']}\tmissed in {m} of {r}" + ("\t(has a human row)" if t in humans else ""))
    if a.apply:
        for t, g, (r, m) in weak:
            if t not in humans:
                rows.append({"ja": t, "en": "", "kind": g["kind"], "variants": "", "source": "human",
                             "note": f"demoted (glossary-weak): Global's official English misses '{g['en']}' in {m} of {r} rows"})
        rows.sort(key=lambda r: (r["ja"], GLOSSARY_RANK[r["source"]], r["en"]))
        write_if_changed(ctx.path("glossary.tsv"), tsv_text(GLOSSARY_COLS, rows))
        rebuild(ctx, a)
    return 0


def glossary_dict(rows):
    """{ja: {"en", "variants", "kind", "source"}}: per term the human row, else the official, else the
    machine one (M2's new names). A row with an empty en removes the term."""
    best = {}
    for r in rows:
        cur = best.get(r["ja"])
        if cur is None or GLOSSARY_RANK[r["source"]] < GLOSSARY_RANK[cur["source"]]:
            best[r["ja"]] = r
    return {ja: {"en": r["en"], "variants": [v for v in r["variants"].split(" | ") if v],
                 "kind": r["kind"], "source": r["source"]}
            for ja, r in sorted(best.items()) if r["en"]}


# ---------------------------------------------------------------- build

class Built:
    pass


def finish(ctx, glossary, source, en, ja):
    """(served English in the master encoding, problems) of one candidate for a JP row (`ja` in the
    master encoding; "" for a new message_id). Folding, %% in printf rows, and for derived rows a
    re-break when Global dropped the Japanese row's line breaks (english.md 3.2: the 459 rows);
    Global's own line breaks are kept."""
    font = ctx.fnt
    jn = C.unesc(ja)
    e = C.unesc(en)
    if source in HUMAN:
        e = unicodedata.normalize("NFC", e)
    e = font.fold(e)
    e = C.fix_percent(e, ja)
    rebroken = False
    if source in DERIVED and "\n" in jn and "\n" not in e:
        e = font.rebreak(e, max(font.widest(jn), 200))
        rebroken = True
    if not ja:  # a new message_id (client strings): no Japanese to compare tokens with
        probs = C.check(e, e, font)
    else:
        probs = C.check(jn, e, font, glossary if source not in DERIVED else None,
                        tags="strict" if source in MACHINE else "subset")
    return C.esc(e), probs, rebroken


class Derived:
    """The part of a build that depends only on the master DBs and the font: per JP row its class
    and its official / memory / template candidate, already finished and checked. Cached per Sources
    (they are read-only), so the edit commands and the tests rebuild quickly."""

    def __init__(self, ctx):
        src, font = ctx.src, ctx.fnt
        mem = C.Memory(src)
        self.rows = {}        # mid -> (ja, sha1, klass, [(source, en, probs, rebroken, (ja px, en px) or None)])
        self.e3, self.token_gaps, self.q7 = [], [], []
        self.official = {}    # mid -> Global's English as stored (for the human override list)
        # mid -> rule ("id-ws" | "memory-ws") of the white-space-insensitive matches (english.md
        # 7.9 id-ws, memory-ws): served as official / memory, listed by `report` (matched.tsv)
        self.matched = {}
        for mid in sorted(src.jp_rows):
            ja = src.jp_rows[mid] or ""
            jn = C.unesc(ja)
            cands = []
            off = src.official(mid, ja)
            rule = C.same_ja(src.gl_ja.get(mid), ja)
            klass = None
            if off is not None:
                klass = "official"
                cands.append(("official", off))
            else:
                e3, why = src.official_e3(mid, ja)
                if e3 is not None:
                    klass = "official_e3"
                    self.e3.append(mid)
                    cands.append(("official", e3))
                elif why:
                    self.token_gaps.append((mid, ja, src.gl_en[mid], why))
            if klass is not None and rule == "id-ws":
                self.matched[mid] = "id-ws"
            if klass is None:
                if not C.has_kana(ja):
                    klass = "neutral"
                else:
                    m, kind = mem.lookup(ja)
                    if m is not None:
                        klass = kind
                        cands.append(("template" if kind == "template" else "memory", m))
                        if kind == "exact_ws":
                            self.matched[mid] = "memory-ws"
                    else:
                        klass = "gap"
            if cands and cands[0][0] == "official":
                self.official[mid] = cands[0][1]
            if C.has_kana(ja) and src.gl_english(mid) and not rule:
                self.q7.append(mid)  # Global's English translates an older Japanese text (Q7)
            done = []
            for source, en in cands:
                e, probs, rebroken = finish(ctx, None, source, en, ja)
                done.append((source, e, probs, rebroken, widths(font, jn, C.unesc(e))))
            self.rows[mid] = (ja, C.sha1(ja), klass, done)

    @staticmethod
    def of(ctx):
        cache = ctx.src.__dict__.setdefault("_english_derived", {})
        key = str(ctx.font)
        if key not in cache:
            cache[key] = Derived(ctx)
        return cache[key]


def widths(font, jn, en):
    """(ja px, en px) of a single-line row, else None."""
    if "\n" in jn or "\n" in en:
        return None
    return font.widest(jn), font.widest(en)


def build(ctx):
    """Everything `build` and `report` need, computed in memory."""
    src, font = ctx.src, ctx.fnt
    d = Derived.of(ctx)
    g_rows = glossary_rows(ctx)
    glossary = glossary_dict(g_rows)
    table = ctx.table()
    client = read_tsv(ctx.path("client-strings.tsv"), CLIENT_COLS)
    b = Built()
    b.glossary_rows, b.glossary = g_rows, glossary
    b.table = table
    b.out = {}            # mid -> (ja_sha1, en, source)
    b.klass = {}          # mid -> official | official_e3 | exact | exact_ws | template | neutral | gap
    b.candidates = collections.Counter()
    b.served = collections.Counter()
    b.failures = []       # {message_id, source, en, problems}
    b.token_gaps = d.token_gaps  # (mid, ja, gl_en, reason)
    b.stale = []          # (mid, source, table sha1, current sha1)
    b.width = []          # (mid, source, ja px, en px): single-line rows over 1.5x the Japanese
    b.width_all = []      # the same for every single-line row
    b.overrides = []      # (mid, source, official en, served en)
    b.rebroken = collections.Counter()
    b.e3, b.q7, b.matched = d.e3, d.q7, d.matched
    b.ours = {}           # mid -> (ja_sha1, en, source): our rows (table + client strings) that pass
    for mid, (ja, h, klass, derived) in d.rows.items():
        cands = []
        t = table.get(mid)
        if t and t["ja_sha1"] != h:
            b.stale.append((mid, t["source"], t["ja_sha1"], h))
            t = None
        if t and t["source"] in HUMAN:
            cands.append((t["source"], t["en"]))
        cands += derived
        if t and t["source"] in MACHINE:
            cands.append((t["source"], t["en"]))
        b.klass[mid] = klass
        b.candidates[klass] += 1
        if t and t["source"] in MACHINE and mid not in b.ours:
            e, probs, _ = finish(ctx, glossary, t["source"], t["en"], ja)
            if not probs:
                b.ours[mid] = (h, e, t["source"])  # committed even where a derived row wins
        for c in cands:
            if len(c) == 2:  # a table row: finish it now (the glossary may have changed)
                source = c[0]
                e, probs, rebroken = finish(ctx, glossary, source, c[1], ja)
                w = widths(font, C.unesc(ja), C.unesc(e))
                if not probs:
                    b.ours[mid] = (h, e, source)
            else:
                source, e, probs, rebroken, w = c
            if probs:
                b.failures.append({"message_id": mid, "source": source, "en": e, "problems": probs})
                continue
            b.out[mid] = (h, e, source)
            b.served[source] += 1
            if rebroken:
                b.rebroken[source] += 1
            off = d.official.get(mid)
            if source in HUMAN and off is not None and C.esc(C.unesc(off)) != e:
                b.overrides.append((mid, source, off, e))
            if w:
                b.width_all.append((mid, source, w[0], w[1]))
                if w[1] > 1.5 * max(w[0], 100):
                    b.width.append((mid, source, w[0], w[1]))
            break
    # new message_ids: master.tsv human rows without a JP row, then the client's strings
    extra = {}
    for r in client:
        extra[r["message_id"]] = ("human", r["en"])
    for mid, t in sorted(table.items()):
        if mid in src.jp_rows:
            continue
        if t["ja_sha1"] or t["source"] not in HUMAN:
            b.stale.append((mid, t["source"], t["ja_sha1"], ""))
            continue
        extra[mid] = (t["source"], t["en"])
    for mid in sorted(extra):
        source, en = extra[mid]
        if mid in src.jp_rows:
            b.failures.append({"message_id": mid, "source": source, "en": en,
                               "problems": {"id": "a client string's id is a JP master message_id"}})
            continue
        e, probs, _ = finish(ctx, glossary, source, en, "")
        if probs:
            b.failures.append({"message_id": mid, "source": source, "en": e, "problems": probs})
            continue
        b.out[mid] = ("", e, source)
        b.ours[mid] = ("", e, source)
        b.served[source] += 1
        b.candidates["client"] += 1

    def text(rows):
        return tsv_text(OUT_COLS, [{"message_id": m, "ja_sha1": rows[m][0], "en": rows[m][1], "source": rows[m][2]}
                                   for m in sorted(rows, key=lambda m: m.encode())])
    b.master_en = text(b.ours)       # committed: our rows only (the user's decision of 2026-10-07)
    b.master_en_full = text(b.out)   # `derive`: the resolved table, the C++ port's reference
    # committed: our glossary rows only; Global's terms are derived (glossary_rows)
    b.glossary_text = tsv_text(GLOSSARY_COLS, [r for r in g_rows if r["source"] != "official"])
    return b


def write_build(ctx, b):
    ch = write_if_changed(ctx.path("master-en.tsv"), b.master_en)
